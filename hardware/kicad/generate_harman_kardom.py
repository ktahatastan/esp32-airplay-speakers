def build_schematic():
    schematic = ksa.create_schematic("harman-kardom")
    schematic.set_paper_size("A3")
    schematic.set_title_block(
        title="Harman Kardom - Single Speaker, Module Level",
        date=SHEET_DATE, rev=SHEET_REV, company="Harman Kardom",
        comments={
            1: "USB-C PD -> XL4015 16.80 V CC/CV -> 4S BMS | ESP32-S3 N16R8 | PCM5102A | XH-A232 bi-amp",
            2: "DO NOT ENERGISE DRIVERS BEFORE G0-G2. BTL OUTPUT NEGATIVES ARE NOT GROUND.",
            3: "V1 does not play audio while charging (ADR-0004). XL4015 termination unproven (ADR-0009).",
            4: "Generated by hardware/kicad/generate_harman_kardom.py - do not hand-edit the output.",
        },
    )
    builder = Builder(schematic)

    for title, start, end in SECTIONS:
        schematic.add_rectangle(point(*start), point(*end), stroke_width=0.35)
        schematic.add_text(title, point((start[0] + end[0]) / 2, start[1] + 3), size=2.2, bold=True)

    for module in MODULES:
        builder.add_module(module)

    draw_charge_stage(builder)
    draw_pack_and_protection(builder)
    draw_logic_supply(builder)
    draw_user_interface(builder)
    draw_audio_chain(builder)
    draw_test_points(builder)

    # Rails that would otherwise need a wire across the whole sheet.
    for index, (net, position) in enumerate((
        ("VBAT_SW", (290, 46)), ("V5_LOGIC", (110, 96)), ("ESP_3V3", (128, 120)),
        ("POWER_GND", (290, 56)), ("STAR_GND", (110, 120)), ("DAC_AGND", (250, 128)),
    )):
        pin = builder.power(net, position, f"#PWR{index:02d}")
        builder.schematic.add_label(net, pin=(f"#PWR{index:02d}", "1"), size=1.0)
        del pin

    schematic.add_text(
        "G0 driver impedance BLOCKED | G1 dummy-load amp BLOCKED | G2 tweeter HPF and C_SAFE BLOCKED | "
        "G3 power, ripple, EMI BLOCKED | G4 battery, charge termination, NTC BLOCKED",
        point(30, 254), size=1.4, bold=True)
    schematic.add_text(
        "Module connectors show a logical interface, not a seller board's physical pin order. "
        "Confirm every silkscreen and datasheet before wiring hardware.",
        point(30, 258), size=1.27)
    return schematic


