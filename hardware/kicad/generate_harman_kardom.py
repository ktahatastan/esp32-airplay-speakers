@dataclass(frozen=True)
class Module:
    """A purchased board drawn as a generic connector.

    `pins` is the logical pin order. It is the interface contract for this
    design, not the physical header order of any specific seller revision.
    """

    reference: str
    value: str
    position: tuple[float, float]
    pins: tuple[str, ...]

    @property
    def size(self) -> int:
        return len(self.pins)

    def index(self, name: str) -> str:
        matches = [i for i, pin in enumerate(self.pins, start=1) if pin == name]
        if not matches:
            raise KeyError(f"{self.reference} has no pin on net {name!r}")
        if len(matches) > 1:
            raise KeyError(
                f"{self.reference} has {len(matches)} pins on net {name!r}; "
                "look the pin up by number instead of by net name")
        return str(matches[0])


