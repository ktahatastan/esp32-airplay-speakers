@dataclass
class Builder:
    """Thin wrapper that keeps pin lookups and wiring in one place."""

    schematic: object
    modules: dict[str, Module] = field(default_factory=dict)

    # -- placement ---------------------------------------------------------
    def add_module(self, module: Module) -> None:
        self.schematic.components.add(
            lib_id=f"Connector_Generic:Conn_01x{module.size:02d}",
            reference=module.reference,
            value=module.value,
            position=point(*module.position),
        )
        self.modules[module.reference] = module
        for number, net in enumerate(module.pins, start=1):
            self.schematic.add_label(net, pin=(module.reference, str(number)), size=1.0)

    def add_part(self, lib_id: str, reference: str, value: str,
                 position: tuple[float, float], rotation: float = 0.0) -> None:
        self.schematic.components.add(lib_id=lib_id, reference=reference, value=value,
                                      position=point(*position), rotation=rotation)

    # -- lookup ------------------------------------------------------------
    def pin(self, reference: str, pin_number: str) -> tuple[float, float]:
        located = self.schematic.get_component_pin_position(reference, pin_number)
        if located is None:
            raise RuntimeError(f"pin {reference}.{pin_number} could not be located")
        return (float(located.x), float(located.y))

    def module_pin(self, reference: str, net: str) -> tuple[float, float]:
        return self.pin(reference, self.modules[reference].index(net))

    # -- connectivity ------------------------------------------------------
    def label(self, reference: str, pin_number: str, net: str) -> None:
        self.schematic.add_label(net, pin=(reference, pin_number), size=1.0)

    def wire(self, start: tuple[float, float], end: tuple[float, float]) -> None:
        self.schematic.add_wire(start, end)

    def route(self, start: tuple[float, float], end: tuple[float, float], channel: float) -> None:
        """Orthogonal horizontal-vertical-horizontal route through `channel`."""
        x = on_grid(channel)
        self.wire(start, (x, start[1]))
        self.wire((x, start[1]), (x, end[1]))
        self.wire((x, end[1]), end)

    def junction(self, position: tuple[float, float]) -> None:
        self.schematic.junctions.add(point(*position))

    def power(self, net: str, position: tuple[float, float], reference: str) -> tuple[float, float]:
        """Place a power symbol and return its pin, ready to wire."""
        lib_id = "power:GND" if net in ("POWER_GND", "STAR_GND", "PD_GND", "DAC_AGND") else "power:PWR_FLAG"
        self.add_part(lib_id, reference, net, position)
        return self.pin(reference, "1")

    def text(self, message: str, position: tuple[float, float], *,
             size: float = 1.27, bold: bool = False) -> None:
        self.schematic.add_text(message, point(*position), size=size, bold=bold)


def draw_charge_stage(builder: Builder) -> None:
    """USB-C PD inlet, 20 V trigger, XL4015 CC/CV stage and the charge fuse."""
    builder.wire(builder.module_pin("J1", "USB_PD_VBUS"), builder.module_pin("U1", "USB_PD_VBUS"))
    builder.wire(builder.module_pin("U1", "PD20V"), builder.module_pin("U2", "PD20V"))
    # Ground hops are addressed by pin number: each converter carries POWER_GND on
    # both an input and an output pin, which is physically one plane inside the module.
    builder.wire(builder.pin("J1", "2"), builder.pin("U1", "2"))
    builder.wire(builder.pin("U1", "4"), builder.pin("U2", "2"))

    builder.add_part("Device:Fuse", "F2", "F_CHG / 3 A CANDIDATE", (196, 30), rotation=90)
    builder.label("F2", "1", "CHG_16V8")
    builder.label("F2", "2", "PACK_POS")

    builder.text("Set the PD trigger to 20 V and calibrate the XL4015 to 16.80 V / 2.00 A "
                 "WITH THE BATTERY DISCONNECTED.", (30, 62))
    builder.text("XL4015 HAS NO GUARANTEED CHARGE TERMINATION. Measure the CV current decay at G4; "
                 "no unattended charging before that.", (30, 66), bold=True)


