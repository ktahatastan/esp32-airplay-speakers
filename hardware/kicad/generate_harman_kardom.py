#!/usr/bin/env python3
"""Generate the Harman Kardom single-speaker KiCad schematic.

This is the electrical source of truth: real symbols, drawn wires, junctions
and power ports, so KiCad ERC actually checks connectivity instead of trusting
a wall of net labels. The readable one-page overview for documentation is a
separate artefact, generated by hardware/diagrams/generate_schematic_svg.py.

    python3 hardware/kicad/generate_harman_kardom.py            # write sources
    python3 hardware/kicad/generate_harman_kardom.py --validate # + ERC and PDF

Conventions used throughout
---------------------------
* Everything is placed on a 2.54 mm grid. kicad-sch-api snaps placements to the
  1.27 mm grid, so an off-grid placement would silently move a pin and leave a
  wire hanging next to it instead of on it. `GRID` and `on_grid()` enforce this.
* Wire endpoints are never hardcoded. They come from
  `schematic.get_component_pin_position()`, so the drawing stays correct even
  if a stock symbol's internal geometry differs from what we assumed.
* Purchased modules are drawn as connectors. Their pin ORDER is a logical design
  contract, not a claim about a seller board's physical header. Verify every
  silkscreen and datasheet before wiring hardware.
* Rails that would otherwise need a wire across the sheet use power symbols.
  Local connections are drawn as real wires.

Safety notes carried on the sheet itself
----------------------------------------
* BTL amplifier outputs are not ground. Never clip a scope ground to them.
* Drivers are not energised before G0-G2.
* V1 does not play audio while charging (ADR-0004).
* The XL4015 stage has no guaranteed charge termination (ADR-0009).
"""

