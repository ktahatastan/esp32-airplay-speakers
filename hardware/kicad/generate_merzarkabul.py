def self_check(schematic) -> list[str]:
    """Structural checks that do not need KiCad installed.

    Catches the failure this drawing is most exposed to: a wire that renders
    next to a pin instead of on it, which looks connected but is not.
    """
    problems: list[str] = []

    pins: dict[tuple[float, float], str] = {}
    for component in schematic.components.all():
        # Probing past the last pin makes the library log a warning, so the pin
        # count is derived from the symbol name instead of discovered by trial.
        lib_id = str(getattr(component, "lib_id", ""))
        if lib_id.startswith("Connector_Generic:Conn_01x"):
            count = int(lib_id[-2:])
        elif lib_id.startswith(("power:", "Connector:TestPoint")):
            count = 1
        else:
            count = 2
        for number in range(1, count + 1):
            located = schematic.get_component_pin_position(component.reference, str(number))
            if located is None:
                problems.append(f"{component.reference}.{number} could not be located")
                continue
            pins[(round(float(located.x), 2), round(float(located.y), 2))] = f"{component.reference}.{number}"

    endpoints: set[tuple[float, float]] = set()
    for wire in schematic.wires:
        for end in (wire.start, wire.end):
            endpoints.add((round(float(end.x), 2), round(float(end.y), 2)))
    for endpoint in sorted(endpoints):
        if endpoint not in pins and not any(
            endpoint in (a, b) for a, b in _corner_pairs(schematic)
        ):
            problems.append(f"wire endpoint {endpoint} is neither a pin nor a routed corner")

    # Two different nets on one connection point silently merge into a single net.
    # That is how a series resistor gets shorted out while ERC still reports zero
    # errors, so it is checked here rather than left to KiCad.
    by_position: dict[tuple[float, float], set[str]] = {}
    net_sizes: dict[str, int] = {}
    for label in schematic.labels:
        key = (round(float(label.position.x), 2), round(float(label.position.y), 2))
        by_position.setdefault(key, set()).add(label.text)
        net_sizes[label.text] = net_sizes.get(label.text, 0) + 1
    for position, names in sorted(by_position.items()):
        if len(names) > 1:
            problems.append(
                f"{sorted(names)} share the connection point {position}: they become one net, "
                "so anything between them is shorted out")

    for net, size in sorted(net_sizes.items()):
        if size == 1 and net not in EXPECTED_OPEN_NETS:
            problems.append(
                f"net {net!r} has a single connection and is not in EXPECTED_OPEN_NETS; "
                "it is either unwired or a typo")

    numbers = [number for number, _ in TEST_POINTS]
    if numbers != list(range(len(numbers))):
        problems.append(f"test points must be a gapless TP0..TP{len(numbers) - 1} sequence")
    if len({number for number, _ in TEST_POINTS}) != len(TEST_POINTS):
        problems.append("duplicate test point number")

    for number, net in TEST_POINTS:
        if net not in net_sizes:
            problems.append(f"TP{number} names net {net!r}, which exists nowhere in the sheet")

    references = [component.reference for component in schematic.components.all()]
    duplicates = {ref for ref in references if references.count(ref) > 1}
    if duplicates:
        problems.append(f"duplicate reference designators: {sorted(duplicates)}")
    return problems


def _corner_pairs(schematic) -> set[tuple[tuple[float, float], tuple[float, float]]]:
    """Corners produced by orthogonal routing are shared by two wire segments."""
    counts: dict[tuple[float, float], int] = {}
    for wire in schematic.wires:
        for end in (wire.start, wire.end):
            key = (round(float(end.x), 2), round(float(end.y), 2))
            counts[key] = counts.get(key, 0) + 1
    shared = {key for key, count in counts.items() if count > 1}
    return {(key, key) for key in shared}


def locate_kicad_cli(explicit: str | None) -> str:
    if explicit:
        candidate = Path(explicit)
        if candidate.is_file():
            return str(candidate)
        raise FileNotFoundError(f"kicad-cli not found at {candidate}")
    found = shutil.which("kicad-cli")
    if found:
        return found
    searched: list[Path] = []
    if sys.platform.startswith("win"):
        searched = [Path(r"C:\Program Files\KiCad") / v / "bin" / "kicad-cli.exe"
                    for v in ("10.0", "9.0", "8.0")]
    elif sys.platform == "darwin":
        searched = [Path("/Applications/KiCad/kicad.app/Contents/MacOS/kicad-cli")]
    for candidate in searched:
        if candidate.is_file():
            return str(candidate)
    raise FileNotFoundError(
        "kicad-cli not found on PATH. Install KiCad 8 or newer, or pass --kicad-cli <path>.")


#: Fixed namespace for deterministic element UUIDs.
UUID_NAMESPACE = uuid_module.UUID("6f4d1b6e-2a3c-5d8f-9b41-7c2e0a5d3f18")
UUID_PATTERN = re.compile(r"[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}")


def stabilise_uuids(schematic_path: Path) -> int:
    """Replace the library's random UUIDs with deterministic ones.

    The generated schematic is reviewed as a diff whenever it is regenerated and
    committed on a machine with KiCad. Left alone, every run emitted a
    fresh random UUID for every symbol, wire, label and junction, so simply
    re-running the generator produced an ~876 line diff with no design change in
    it, which buries the real change whenever there is one.

    Every UUID in the file is remapped through one table, so cross references
    stay intact: a symbol instance's `(path "/<sheet-uuid>")` still points at the
    sheet it belongs to. Replacing UUIDs one occurrence at a time would silently
    break that link.

    New values are assigned in order of first appearance. The generator is
    deterministic, so an unchanged script yields byte-identical output and the
    file only moves when the drawing actually moves. Inserting an element
    renumbers the ones after it, so review a regeneration diff as regenerated
    output rather than line by line.
    """
    text = schematic_path.read_text(encoding="utf-8")
    mapping: dict[str, str] = {}
    for found in UUID_PATTERN.findall(text):
        if found not in mapping:
            mapping[found] = str(uuid_module.uuid5(UUID_NAMESPACE, f"merzarkabul:{len(mapping)}"))
    stable = UUID_PATTERN.sub(lambda match: mapping[match.group(0)], text)
    schematic_path.write_text(stable, encoding="utf-8")
    return len(mapping)


def write_project(output_dir: Path) -> Path:
    output_dir.mkdir(parents=True, exist_ok=True)
    schematic_path = output_dir / "merzarkabul.kicad_sch"
    project_path = output_dir / "merzarkabul.kicad_pro"
    build_schematic().save(schematic_path)
    stabilise_uuids(schematic_path)
    project = {"board": {}, "boards": [], "cvpcb": {}, "erc": {}, "libraries": {},
               "meta": {"filename": project_path.name, "version": 1}, "net_settings": {},
               "pcbnew": {}, "schematic": {}, "text_variables": {}}
    project_path.write_text(json.dumps(project, indent=2) + "\n", encoding="utf-8")
    return schematic_path


def run_checks(cli: str, schematic_path: Path) -> None:
    report = schematic_path.with_suffix(".erc.rpt")
    pdf = schematic_path.with_suffix(".pdf")
    erc = subprocess.run([cli, "sch", "erc", "--output", str(report), str(schematic_path)], check=False)
    report_text = report.read_text(encoding="utf-8")
    if "Errors 0" not in report_text:
        raise RuntimeError(f"KiCad ERC reported errors; inspect {report}")
    subprocess.run([cli, "sch", "export", "pdf", "--output", str(pdf), str(schematic_path)], check=True)
    print(f"ERC report: {report} (exit {erc.returncode}; unconnected TBD/NC pins are expected warnings)")
    print(f"Preview PDF: {pdf}")


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the Merzarkabul Airplay Speakers KiCad schematic.")
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--validate", action="store_true", help="run KiCad ERC and export a PDF preview")
    parser.add_argument("--kicad-cli", help="explicit kicad-cli executable path")
    args = parser.parse_args()
    try:
        schematic = build_schematic()
        problems = self_check(schematic)
        for problem in problems:
            print(f"SELF-CHECK: {problem}", file=sys.stderr)
        if problems:
            return 1
        schematic_path = write_project(args.output_dir.resolve())
        print(f"Generated: {schematic_path}")
        print(f"Modules: {len(MODULES)} | test points: {len(TEST_POINTS)} | "
              f"self-check: {len(problems)} problems | deterministic output")
        if args.validate:
            run_checks(locate_kicad_cli(args.kicad_cli), schematic_path)
    except (FileNotFoundError, OSError, RuntimeError, subprocess.CalledProcessError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
