@dataclass
class Builder:
    """Thin wrapper that keeps pin lookups and wiring in one place."""

    schematic: object
    modules: dict[str, Module] = field(default_factory=dict)

    # -- placement ---------------------------------------------------------
    def add_module(self, module: Module) -> None:
        self.schematic.components.add(
            lib_id=f"Connector_Generic:Conn_01x{module.size:02d}",
            reference=module.reference,
            value=module.value,
            position=point(*module.position),
        )
        self.modules[module.reference] = module
        for number, net in enumerate(module.pins, start=1):
            self.schematic.add_label(net, pin=(module.reference, str(number)), size=1.0)

    def add_part(self, lib_id: str, reference: str, value: str,
                 position: tuple[float, float], rotation: float = 0.0) -> None:
        self.schematic.components.add(lib_id=lib_id, reference=reference, value=value,
                                      position=point(*position), rotation=rotation)

    # -- lookup ------------------------------------------------------------
    def pin(self, reference: str, pin_number: str) -> tuple[float, float]:
        located = self.schematic.get_component_pin_position(reference, pin_number)
        if located is None:
            raise RuntimeError(f"pin {reference}.{pin_number} could not be located")
        return (float(located.x), float(located.y))

    def module_pin(self, reference: str, net: str) -> tuple[float, float]:
        return self.pin(reference, self.modules[reference].index(net))

    # -- connectivity ------------------------------------------------------
    def label(self, reference: str, pin_number: str, net: str) -> None:
        self.schematic.add_label(net, pin=(reference, pin_number), size=1.0)

    def wire(self, start: tuple[float, float], end: tuple[float, float]) -> None:
        self.schematic.add_wire(start, end)

    def route(self, start: tuple[float, float], end: tuple[float, float], channel: float) -> None:
        """Orthogonal horizontal-vertical-horizontal route through `channel`."""
        x = on_grid(channel)
        self.wire(start, (x, start[1]))
        self.wire((x, start[1]), (x, end[1]))
        self.wire((x, end[1]), end)

    def junction(self, position: tuple[float, float]) -> None:
        self.schematic.junctions.add(point(*position))

    def power(self, net: str, position: tuple[float, float], reference: str) -> tuple[float, float]:
        """Place a power symbol and return its pin, ready to wire."""
        lib_id = "power:GND" if net in ("POWER_GND", "STAR_GND", "DAC_AGND") else "power:PWR_FLAG"
        self.add_part(lib_id, reference, net, position)
        return self.pin(reference, "1")

    def text(self, message: str, position: tuple[float, float], *,
             size: float = 1.27, bold: bool = False) -> None:
        self.schematic.add_text(message, point(*position), size=size, bold=bold)


def draw_dc_input(builder: Builder) -> None:
    """Barrel jack, the reverse-polarity candidate and the bulk capacitor."""
    # D2 sits between the jack and VIN. It is a candidate: G1 decides between a
    # Schottky, an ideal-diode module and a plain 0 R link from the measured
    # drop and temperature. Whichever it is, the part has to exist in the
    # netlist -- without it DC_IN and VIN would be two nets with nothing between
    # them, and the sheet would draw an open circuit that ERC cannot see.
    # Device:D pin 1 is the cathode, pin 2 the anode; rotated so current flows
    # from the jack on the left towards the rail on the right.
    builder.add_part("Device:D_Schottky", "D2",
                     "REVERSE-POLARITY CANDIDATE / SCHOTTKY OR IDEAL DIODE OR 0 R LINK / DECIDE AT G1",
                     (100, 30), rotation=180)
    builder.label("D2", "2", "DC_IN")
    builder.label("D2", "1", "VIN")
    builder.route(builder.module_pin("J1", "DC_IN"), builder.pin("D2", "2"), 75)

    builder.add_part("Device:C_Polarized", "C1", "C_A / 1000 uF / 35 V / 105 C LOW-ESR TARGET", (150, 36))
    builder.label("C1", "1", "VIN")
    builder.label("C1", "2", "POWER_GND")
    builder.route(builder.pin("D2", "1"), builder.pin("C1", "1"), 130)

    builder.text("VERIFY CENTRE-POSITIVE POLARITY AT THE JACK WITH A METER BEFORE THE FIRST POWER-UP (G1). "
                 "Reading the adapter label is not a measurement.", (30, 58), bold=True)
    builder.text("MEASURE THE ADAPTER'S NO-LOAD OUTPUT BEFORE CONNECTING IT: below 25.5 V or it is refused. 24 V sits "
                 "2 V under the TPA3110's 26 V maximum (G1). 24 V is inside both windows: TPA3110 8-26 V, MP1584 4.5-28 V.", (30, 62), bold=True)
    builder.text("The adapter is given: 24 V / 2.9 A (about 70 W). The limiter ceiling is derived from that budget with all four "
                 "amps driven and verified by VIN sag in G1. No power switch in V1: unplug the adapter to turn off.", (30, 66))
    builder.text("First energisation from a current-limited lab supply, not the adapter. C_A is one part at the jack; "
                 "per-amp bulk only if the G1 ripple measurement asks for it. D2 at 2.9 A dissipates about 1 W or more.", (30, 69))


